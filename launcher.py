def discovery_server_address():
    """The configured FastDDS discovery server address ("host:port")."""
    server = "10.42.0.1:11811"
    try:
        with open(CONFIG_PATH, "r") as f:
            net = (yaml.safe_load(f) or {}).get("network", {}) or {}
        server = str(net.get("discovery_server", server))
    except Exception:
        pass
    return server


def _discovery_server_running():
    """True if a fast-discovery-server process is running on THIS machine."""
    try:
        return subprocess.run(["pgrep", "-f", "fast-discovery-server"],
                              stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                              timeout=5).returncode == 0
    except Exception:
        return False


def resolve_discovery_server():
    """Return (server, local_ip) for the wireless path, or (None, None) for cable.

    The robot's WiFi AP drops multicast, so DDS discovery never completes over
    wireless even though ping is fine — `ros2 topic list` just comes back empty.
    A discovery server on the robot replaces multicast with unicast client/server.
    On cable multicast works, so this stays off there.

    config.yaml -> network.discovery_mode: auto (default) | on | off
    """
    server, mode = discovery_server_address(), "auto"
    try:
        with open(CONFIG_PATH, "r") as f:
            net = (yaml.safe_load(f) or {}).get("network", {}) or {}
        mode = str(net.get("discovery_mode", mode)).lower()
    except Exception:
        pass

    if mode == "off":
        return None, None

    # auto: only when this machine sits on the server's subnet, i.e. it joined the
    # robot's hotspot rather than the wired network. connect() on a UDP socket
    # sends nothing — it just resolves which local address the route would use.
    host, _, port = server.partition(":")
    try:
        sock = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)
        sock.settimeout(0.2)
        sock.connect((host, int(port or 11811)))
        local_ip = sock.getsockname()[0]
        sock.close()
    except Exception:
        return (server, None) if mode == "on" else (None, None)

    if mode == "on":
        return server, local_ip

    if local_ip == host:
        # This machine hosts the discovery server - the robot, which is also the
        # AP and therefore ALWAYS holds this address. Subnet checks cannot tell
        # WiFi from cable here, so ask the process table instead: the server
        # would be running locally. Running it is the operator's way of saying
        # "we are on wireless", which is exactly the intent we want to follow.
        return (server, local_ip) if _discovery_server_running() else (None, None)

    same_subnet = local_ip.rsplit(".", 1)[0] == host.rsplit(".", 1)[0]
    return (server, local_ip) if same_subnet else (None, None)


def write_fastdds_profile(local_ip):
    """Pin FastDDS to one interface; returns the profile path, or None.

    Both machines are multi-homed (several wired subnets plus the robot's WiFi
    AP). A participant otherwise advertises every address it owns, the peer picks
    one that does not route, and data silently never arrives even though
    discovery succeeded and `ros2 topic info` shows the endpoints. Generated at
    runtime from the address that actually reaches the robot, so there is nothing
    machine-specific stored in the repo.
    """
    if not local_ip:
        return None
    path = os.path.join(tempfile.gettempdir(),
                        "quadruped_fastdds_%s.xml" % local_ip.replace(".", "_"))
    xml = """<?xml version="1.0" encoding="UTF-8" ?>
<!-- Generated by launcher.py. Restricts FastDDS to %s. -->
<dds>
  <profiles xmlns="http://www.eprosima.com/XMLSchemas/fastRTPS_Profiles">
    <transport_descriptors>
      <transport_descriptor>
        <transport_id>iface_udp</transport_id>
        <type>UDPv4</type>
        <interfaceWhiteList>
          <address>%s</address>
        </interfaceWhiteList>
      </transport_descriptor>
    </transport_descriptors>
    <participant profile_name="iface_only" is_default_profile="true">
      <rtps>
        <userTransports><transport_id>iface_udp</transport_id></userTransports>
        <useBuiltinTransports>false</useBuiltinTransports>
      </rtps>
    </participant>
  </profiles>
</dds>
""" % (local_ip, local_ip)
    try:
        with open(path, "w") as f:
            f.write(xml)
        return path
    except Exception:
        return None


def ckpt_display_name(path):
    """Extract the run folder name from a full checkpoint path."""
    parts = path.replace("\\", "/").split("/")
    for i, p in enumerate(parts):
        if p == "checkpoints" and i > 0:
            return parts[i - 1]
    return os.path.join(*parts[-3:-1]) if len(parts) >= 3 else path

