    if training_phase:
        display_phase = ", ".join(training_phase) if isinstance(training_phase, list) else str(training_phase)
        print(f"Phase:    {display_phase}")
    if ckpt:
        print(f"Checkpoint: {ckpt_display_name(ckpt)}")
    print(f"Teleop:   {teleop}")
    print("=" * 50 + "\n")

    # Set up environment variables
    env = os.environ.copy()
    env["ROS_DOMAIN_ID"] = str(domain_id)

    # ROS 2 discovery: multicast on cable, discovery server over the robot's WiFi AP.
    discovery_server, discovery_local_ip = resolve_discovery_server()
    if discovery_server:
        env["ROS_DISCOVERY_SERVER"] = discovery_server
        # Without this the CLI only sees topics it matched itself, so `ros2 topic
        # list` looks broken even when discovery is working.
        env["ROS_SUPER_CLIENT"] = "TRUE"
        print(f"[Launcher] Wireless path detected -> ROS_DISCOVERY_SERVER={discovery_server}")
        profile = write_fastdds_profile(discovery_local_ip)
        if profile:
            env["FASTRTPS_DEFAULT_PROFILES_FILE"] = profile
            print(f"[Launcher] FastDDS pinned to {discovery_local_ip} ({profile})")
        print(f"[Launcher] Requires 'fast-discovery-server -i 0 -l {discovery_server.replace(':', ' -p ')}' on the robot.")
    else:
        # Be authoritative: a stale export from a previous wireless session would
        # otherwise break discovery once you are back on cable.
        env.pop("ROS_DISCOVERY_SERVER", None)
        env.pop("ROS_SUPER_CLIENT", None)
        # Only drop a profile we generated - never a hand-picked one.
        if "quadruped_fastdds_" in env.get("FASTRTPS_DEFAULT_PROFILES_FILE", ""):
            env.pop("FASTRTPS_DEFAULT_PROFILES_FILE", None)

    if (discovery_server or None) != (os.environ.get("ROS_DISCOVERY_SERVER") or None):
        # The daemon caches the previous discovery view across cable/WiFi switches.
        try:
            subprocess.run(["ros2", "daemon", "stop"], env=env, timeout=10,
                           stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        except Exception:
            pass
    env["QUADRUPED_ROBOT_CFG"] = robot_cfg
    env["QUADRUPED_ROBOT"] = robot_cfg
    if teleop:
        env["QUADRUPED_TELEOP"] = "1"
    if training_phase:
        env["QUADRUPED_TRAINING_PHASE"] = ", ".join(training_phase) if isinstance(training_phase, list) else str(training_phase)
    
    # Search for OBS_DIM in the same folder as the checkpoint
    if ckpt:
        ckpt_dir = os.path.dirname(ckpt)
        params_dir = os.path.abspath(os.path.join(ckpt_dir, "..", "params"))
        agent_cfg = os.path.join(params_dir, "agent.yaml")
        env_cfg_path = os.path.join(params_dir, "env.yaml")
        obs_dim = 0
        
        # Try agent.yaml first
        if os.path.exists(agent_cfg):
            try:
                with open(agent_cfg, 'r') as f:
                    data = yaml.load(f, Loader=yaml.UnsafeLoader)
                    obs_dim = data.get("models", {}).get("policy", {}).get("input_shape", [0])[0]
            except Exception:
                pass
                
        # Try env.yaml if not found in agent.yaml
        if not obs_dim and os.path.exists(env_cfg_path):
            try:
                with open(env_cfg_path, 'r') as f:
                    data = yaml.load(f, Loader=yaml.UnsafeLoader)
                    obs_dim = data.get("observation_space", 0)
            except Exception:
                pass
                
